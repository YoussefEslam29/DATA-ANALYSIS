X = full_data.drop(cols_to_drop, axis=1)
y = full_data["Class"]

# 3. Create a random, non-repeating 80/20 split
X_train, X_val, y_train, y_val = train_test_split(
    X, y,
    test_size=0.20,  # 80/20 split
    random_state=42, # 42 ensures the random split is non-repeating across reruns
    stratify=y       # Ensures class proportions remain balanced
)

# 4. Drop the same redundant columns from the final test set so dimensions match later
cols_to_drop_test = [c for c in ["ConvexArea", "EquivDiameter"] if c in test.columns]
test = test.drop(cols_to_drop_test, axis=1)

"""###10:**Feature** Scaling"""

