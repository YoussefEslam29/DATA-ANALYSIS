# 3. Assess Model Fit
def evaluate_model_fit(train_acc, test_acc, threshold=0.04):
    diff = train_acc - test_acc
    if diff > threshold:
        return "Overfitted (Train accuracy is significantly higher than Test accuracy)"
    elif train_acc < 0.70 and test_acc < 0.70:
        return "Underfitted (Both Train and Test accuracies are low)"
    else:
        return "Reasonably Fitted (Good generalization, margins are tight)"

